#!/usr/bin/env python3
"""
FILE:    gen_context_map.py
MODULE:  tools
PURPOSE: Builds docs/CONTEXT_MAP.md: one line per module (from its MODULE.md first line)
         plus the file list with each file's PURPOSE line. Lets an LLM pick what to open.
DEPENDS: MODULE.md files, file headers
USED BY: CI, angel-dev agent
NOTES:   Module = any dir containing MODULE.md or build.gradle.kts under app/core/feature/data/backend.
"""
import pathlib, re
ROOT = pathlib.Path(__file__).resolve().parent.parent
TOP = ["app", "core", "feature", "data", "backend"]
out = ["# Context Map (generated by tools/gen_context_map.py - do not edit)", ""]
mods = set()
for t in TOP:
    for p in (ROOT / t).rglob("*"):
        if p.name in ("MODULE.md", "build.gradle.kts") and "build" not in p.parent.parts[len(ROOT.parts):-1]:
            mods.add(p.parent)
for m in sorted(mods):
    rel = m.relative_to(ROOT)
    md = m / "MODULE.md"
    line = md.read_text().splitlines()[0].lstrip("# ").strip() if md.exists() else "(no MODULE.md yet)"
    out.append(f"## {rel}\n{line}")
    for f in sorted(m.rglob("*.kt")):
        if "build" in f.parts: continue
        mt = re.search(r"PURPOSE:\s*(.+)", "\n".join(f.read_text(errors="ignore").splitlines()[:25]))
        out.append(f"- `{f.relative_to(m)}`: {mt.group(1).strip() if mt else '(no header)'}")
    out.append("")
(ROOT / "docs" / "CONTEXT_MAP.md").write_text("\n".join(out) + "\n")
print(f"context map: {len(mods)} modules")
